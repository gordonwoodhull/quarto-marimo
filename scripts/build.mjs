// Builds the versioned engine bundle (Node/Deno), the browser bundle, and the
// bridge stylesheet. Run from the repository root: esbuild embeds entry paths
// as relative comments, so a fixed working directory keeps the output
// byte-stable.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
process.chdir(root);

const extensionDir = "_extensions/marimo";
const distDir = "dist";
const assetsDir = join(extensionDir, "assets");

const version = readFileSync(join(extensionDir, "_extension.yml"), "utf-8")
  .match(/^version:\s*["']?([^"'\s#]+)["']?\s*$/m)?.[1];
if (!version) throw new Error("marimo extension version is missing");

const common = { bundle: true, write: false, logLevel: "warning", legalComments: "none" };

async function bundle(options) {
  const { outputFiles } = await build({ ...common, ...options });
  return outputFiles[0].text;
}

const engine = await bundle({
  entryPoints: ["src/engine/index.ts"],
  format: "esm",
  platform: "node",
  target: "node24",
  external: ["node:*"],
  // Lets bundled CommonJS dependencies call `require` for node built-ins.
  banner: {
    js: 'import{createRequire as __cr}from"node:module";const require=__cr(import.meta.url);',
  },
});
const browser = await bundle({
  entryPoints: ["src/browser/index.ts"],
  format: "esm",
  platform: "browser",
});
const styles = await bundle({
  entryPoints: ["node_modules/@marimo-team/mdx-marimo/dist/styles.css"],
  loader: { ".css": "css" },
  minify: true,
});

const banner =
  "// Generated by `npm run build` from src/browser and the mdx-marimo bridge.\n" +
  "// Do not edit this file directly.\n";

rmSync(distDir, { recursive: true, force: true });
rmSync(assetsDir, { recursive: true, force: true });
mkdirSync(distDir, { recursive: true });
mkdirSync(assetsDir, { recursive: true });

const outputs = [
  [`marimo-engine-v${version}.js`, engine],
  [`browser-v${version}.js`, banner + browser],
  [`islands-bridge-v${version}.css`, styles],
];
for (const [name, contents] of outputs) {
  writeFileSync(join(distDir, name), contents);
}
// The engine cache sits beside the loader shim; browser assets under assets/.
copyFileSync(join(distDir, outputs[0][0]), join(extensionDir, outputs[0][0]));
for (const [name] of outputs.slice(1)) {
  copyFileSync(join(distDir, name), join(assetsDir, name));
}
console.log(`built quarto-marimo v${version}`);
